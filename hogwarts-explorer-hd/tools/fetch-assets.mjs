#!/usr/bin/env node
// Fetch ONLY CC0 assets (Poly Haven) and commit a small, optimised set (<25 MB).
// The game runs fully without these (procedural fallback); they just add realism.
// Usage:  node tools/fetch-assets.mjs
// Needs network. Optional: `sharp` (npm i sharp) or ImageMagick `convert` for resize.
// Every asset is listed with source + licence in ../CREDITS.md.
import { mkdir, writeFile, readFile, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';

const pexec = promisify(execFile);
const __dir = dirname(fileURLToPath(import.meta.url));
const ASSETS = join(__dir, '..', 'assets');
const TEX = join(ASSETS, 'textures');
const HDRI = join(ASSETS, 'hdri');

// slug -> output filename the game loads (see src/main.js / environment.js).
const TEXTURES = {
  castle_wall_varriation: 'castle_wall_1k.jpg',
  slate_floor:            'slate_roof_1k.jpg',
  wood_floor_deck:        'wood_1k.jpg',
  aerial_grass_rock:      'grass_1k.jpg',
};
const HDRIS = {
  kloofendal_48d_partly_cloudy_puresky: 'kloofendal_day_1k.hdr',
  rogland_clear_night:                  'night_1k.hdr',
  spruit_sunrise:                       'dusk_1k.hdr',
};

async function get(url) {
  const r = await fetch(url, { headers: { 'User-Agent': 'hp-owl-games-hd/1.0 (personal, CC0 only)' } });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r;
}

// Prefer sharp, else ImageMagick, else just write the original bytes.
async function saveImage(buf, out) {
  const { unlink } = await import('node:fs/promises');
  try {
    const sharp = (await import('sharp')).default;
    await sharp(buf).resize(1024, 1024, { fit: 'inside' }).jpeg({ quality: 80 }).toFile(out);
    return 'sharp';
  } catch { /* fall through */ }
  const tmp = out + '.orig';
  await writeFile(tmp, buf);
  try {
    await pexec('convert', [tmp, '-resize', '1024x1024>', '-quality', '80', out]);
    return 'imagemagick';
  } catch {
    await writeFile(out, buf);   // no tool available: keep original (PH 1k is already ~1024px)
    return 'raw';
  } finally {
    await unlink(tmp).catch(() => {});
  }
}

async function fetchTextures() {
  await mkdir(TEX, { recursive: true });
  const done = [];
  for (const [slug, outName] of Object.entries(TEXTURES)) {
    try {
      const files = await (await get(`https://api.polyhaven.com/files/${slug}`)).json();
      const diff = files.Diffuse || files.diffuse || files.albedo || files.Color;
      const url = diff && diff['1k'] && (diff['1k'].jpg?.url || diff['1k'].png?.url);
      if (!url) { console.warn('no 1k diffuse for', slug); continue; }
      const buf = Buffer.from(await (await get(url)).arrayBuffer());
      const how = await saveImage(buf, join(TEX, outName));
      console.log(`texture ${slug} -> ${outName} (${how})`);
      done.push(outName);
    } catch (e) { console.warn('texture failed', slug, e.message); }
  }
  return done;
}

async function fetchHDRIs() {
  await mkdir(HDRI, { recursive: true });
  const done = [];
  for (const [slug, outName] of Object.entries(HDRIS)) {
    try {
      const url = `https://dl.polyhaven.org/file/ph-assets/HDRIs/hdr/1k/${slug}_1k.hdr`;
      const buf = Buffer.from(await (await get(url)).arrayBuffer());
      await writeFile(join(HDRI, outName), buf);
      console.log(`hdri ${slug} -> ${outName} (${(buf.length / 1e6).toFixed(1)}MB)`);
      done.push(outName);
    } catch (e) { console.warn('hdri failed', slug, e.message); }
  }
  return done;
}

async function main() {
  const textures = await fetchTextures();
  const hdri = await fetchHDRIs();
  const manifest = { _note: 'Auto-generated by tools/fetch-assets.mjs — CC0 Poly Haven assets.', textures, hdri };
  await writeFile(join(ASSETS, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  // size guard
  let total = 0;
  for (const d of [TEX, HDRI]) {
    try { for (const f of (await import('node:fs')).readdirSync(d)) total += (await stat(join(d, f))).size; } catch {}
  }
  console.log(`\nManifest written. Committed asset size: ${(total / 1e6).toFixed(1)} MB (budget 25 MB).`);
  if (total > 25e6) console.warn('WARNING: over the 25 MB commit budget — trim assets.');
}

main().catch(e => { console.error(e); process.exit(1); });
